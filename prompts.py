def split_bubbles(text: str, max_bubbles: int = 4) -> list[str]:
    """Разрезает свободный текст ответа на «пузыри» по пустым строкам."""
    if not text:
        return []
    chunks = [chunk.strip() for chunk in text.replace("\r\n", "\n").split("\n\n")]
    bubbles = [c for c in chunks if c]
    if not bubbles:
        flat = text.strip()
        return [flat] if flat else []
    return bubbles[:max_bubbles]


