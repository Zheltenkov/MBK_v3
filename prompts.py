def relevant_product_knowledge(facts: dict | None, user_message: str = "") -> str:
    """Динамическая подгрузка знаний: универсальные стопы и таргеты — всегда; детали по продуктам —
    только те, что релевантны фактам клиента или ключевым словам в его последней реплике.

    Это экономит сотни токенов на типичном ходу и оставляет разговорному вызову меньше «правило-связи»,
    что прямо влияет на живость голоса (см. judge-eval).
    """
    import re

    facts = facts or {}
    msg = (user_message or "").lower()
    assets = facts.get("assets") if isinstance(facts.get("assets"), dict) else {}
    debts = facts.get("debts") if isinstance(facts.get("debts"), dict) else {}
    employment = facts.get("employment") if isinstance(facts.get("employment"), dict) else {}

    selected: list[str] = []

    realty_keywords = ("квартир", "недвижим", "ипотек", " дом", "коммерч", "комнат", "апартам", "таунхаус")
    car_keywords = (
        "машин", "авто", "птс", "тачк", "марка", "год выпуска",
        # популярные марки — клиенты часто их называют первым делом, без слов «машина/авто»
        "тойота", "toyota", "киа", " kia", "хёндай", "хундай", "hyundai",
        "лада", " ваз", "нива", "приора", "гранта", "веста",
        "форд", " ford", "ниссан", "nissan", "мазда", "mazda",
        "бмв", " bmw", "ауди", "audi", "мерседес", "mercedes",
        "рено", "renault", "шкода", "skoda", "опель", "opel",
        "фольксваген", "volkswagen", "geely", "haval", "chery",
    )
    debt_keywords = ("банкрот", "просроч", "не вытяг", "тяну долг", "коллектор", "мфо", "микрозайм")
    has_year_mention = bool(re.search(r"\b(19[89]\d|20[0-2]\d)\b", msg))  # 1980–2029

    has_realty = (
        assets.get("type") == "Недвижимость"
        or isinstance(assets.get("realty"), dict)
        or any(kw in msg for kw in realty_keywords)
    )
    has_car = (
        assets.get("has_car") is True
        or isinstance(assets.get("vehicle"), dict)
        or any(kw in msg for kw in car_keywords)
        or has_year_mention  # «тойота 2015» / «нужно 200к, машина 2010» — год = почти всегда авто
    )
    debt_total = debts.get("total")
    big_debt = isinstance(debt_total, (int, float)) and not isinstance(debt_total, bool) and debt_total >= 300_000
    debt_signals = (
        debts.get("has_current_overdue") is True
        or big_debt
        or any(kw in msg for kw in debt_keywords)
    )
    unsecured_eligible = (
        debts.get("has_mfo") is not True
        and debts.get("has_current_overdue") is not True
        and employment.get("type") not in (None, "", "безработный")
    )

    if has_realty:
        selected.append("realty_collateral")
    if has_car:
        selected.append("pts_loan")
    if debt_signals:
        selected.append("bfl")
    if unsecured_eligible and not debt_signals:
        selected.append("unsecured_loan")

    if not selected:
        # Ничего ещё не зацепилось — даём короткий обзор всех путей + универсальные стопы.
        return PRODUCT_OVERVIEW + "\n\n" + PRODUCT_UNIVERSAL

    parts = ["Релевантные сейчас маршруты (детали для разговора):"]
    for key in selected:
        parts.append(PRODUCT_DETAILS[key])
    parts.append(PRODUCT_UNIVERSAL)
    return "\n\n".join(parts)


# Сборная константа на случай, если где-то ещё импортируется по старому имени.
PRODUCT_KNOWLEDGE = "\n\n".join(
    [PRODUCT_OVERVIEW] + list(PRODUCT_DETAILS.values()) + [PRODUCT_UNIVERSAL]
)


